/**
 * 标准化单个字段名
 * 先做清洁处理，再查别名表，若命中则返回标准名，否则返回原值
 */
export function normalizeFieldName(name: string): string {
  const s = clean(name);
  return ALIASES[s] || s;
}

/**
 * 标准化一条记录的所有字段名
 */
export function normalizeRecordKeys(record: any): any {
  if (!record || typeof record !== 'object') return record;
  const out: any = {};
  for (const [key, value] of Object.entries(record)) {
    const nk = normalizeFieldName(key);
    if (!(nk in out)) out[nk] = value;
  }
  return out;
}

/**
 * 标准化一个数组中的所有记录
 */
export function normalizeRecordsArray(arr: any[]): any[] {
  return arr.map(normalizeRecordKeys);
}
